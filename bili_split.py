# ---- 工具路径解析（环境变量 > PATH，无硬编码本机路径）----
# 可设置: FFMPEG_PATH / YTDLP_PATH / NODE_PATH 指向本机工具
def _tool_path(env_name):
    v = os.environ.get(env_name, "").strip()
    return v or None


FFMPEG_DEFAULT = _tool_path("FFMPEG_PATH")
YTDLP_DEFAULT = _tool_path("YTDLP_PATH")
NODE_DEFAULT = _tool_path("NODE_PATH")

# HuggingFace 模型走国内镜像（首次下载模型时显著加速）
os.environ.setdefault("HF_ENDPOINT", "https://hf-mirror.com")

TS_RE = re.compile(r"^(\d{1,2}:)?(\d{1,2}):(\d{1,2}(?:\.\d+)?)$")


def log(msg):
    print(f"[bili_split] {msg}", flush=True)


def find_exe(name, given, default):
    if given:
        return given
    cands = [default, shutil.which(name)]
    for c in cands:
        if c and os.path.exists(c):
            return c
    env_hint = {"ffmpeg": "FFMPEG_PATH", "yt-dlp": "YTDLP_PATH",
                "node": "NODE_PATH"}.get(name, name.upper() + "_PATH")
    raise SystemExit(
        f"找不到 {name}。请确保已加入 PATH，或设置环境变量 {env_hint}，或用 --{name} 参数指定路径")


def parse_ts(s):
    """'12:34' / '1:02:03.5' -> 秒(float)"""
    m = TS_RE.match(s.strip())
    if not m:
        raise ValueError(f"时间戳格式错误: {s!r} (应为 mm:ss 或 hh:mm:ss)")
    h = int(m.group(1)[:-1]) if m.group(1) else 0
    mi = int(m.group(2))
    se = float(m.group(3))
    return h * 3600 + mi * 60 + se


def parse_cuts(spec):
    """'0:00-12:34, 12:34-25:00' -> [(start, end), ...] 并校验"""
    pairs = []
    for item in spec.split(","):
        item = item.strip()
        if not item:
            continue
        if "-" not in item:
            raise ValueError(f"分段 {item!r} 缺少 '-'，格式应为 起止-结束")
        a, b = item.split("-", 1)
        s, e = parse_ts(a), parse_ts(b)
        if e <= s:
            raise ValueError(f"分段 {item!r} 结束时间必须大于开始时间")
        pairs.append((s, e))
    for i in range(1, len(pairs)):
        if pairs[i][0] < pairs[i - 1][1] - 0.5:
            log(f"警告: 分段{i}与{i-1}时间重叠 ({pairs[i-1][1]} > {pairs[i][0]})")
    return pairs


def run(cmd, **kw):
    log("$ " + " ".join(cmd))
    return subprocess.run(cmd, check=True, **kw)


def ffmpeg_cmd(exe, args):
    return [exe, "-hide_banner", "-loglevel", "error", "-y"] + args


def cut_flac(ffmpeg, src_wav, out_flac, start, end):
    """从解码后的 wav 精确切割为 flac（-ss/-to 放 -i 前, 采样级精确）"""
    run(ffmpeg_cmd(ffmpeg, ["-ss", f"{start:.3f}", "-to", f"{end:.3f}",
                            "-i", src_wav, "-vn", "-c:a", "flac",
                            "-compression_level", "8", out_flac]))


def cut_wav16(ffmpeg, src_wav, out_wav, start, end):
    """切割 16k mono wav 供 whisper 转写"""
    run(ffmpeg_cmd(ffmpeg, ["-ss", f"{start:.3f}", "-to", f"{end:.3f}",
                            "-i", src_wav, "-vn", "-ar", "16000", "-ac", "1",
                            "-c:a", "pcm_s16le", out_wav]))


def detect_site(url):
    """按 URL 识别站点: bilibili / youtube / unknown"""
    u = (url or "").lower().strip()
    if "youtube.com" in u or "youtu.be" in u:
        return "youtube"
    if "bilibili.com" in u or u.startswith("bv"):
        return "bilibili"
    return "unknown"


def netscape_line(domain, name, value, exp, secure="TRUE", path="/"):
    """构造 Netscape cookies.txt 的一行 (yt-dlp 可解析)。value 中的控制字符需清洗。"""
    value = str(value).replace("\t", " ").replace("\r", " ").replace("\n", " ")
    return f"{domain}\tTRUE\t{path}\t{secure}\t{exp}\t{name}\t{value}"


def write_netscape_cookies(path, cookie_str, domain=".bilibili.com"):
    """把粘贴的 cookie 字符串 (如 'SESSDATA=xxx; bili_jct=yyy') 转成 yt-dlp 可用的 Netscape cookies.txt"""
    cookie_str = (cookie_str or "").strip()
    if cookie_str.lower().startswith("cookie:"):
        cookie_str = cookie_str[7:].strip()
    if not cookie_str:
        raise SystemExit("--cookies-text 为空")
    exp = str(int(__import__("time").time()) + 20 * 365 * 86400)
    lines = ["# Netscape HTTP Cookie File", "# generated by bili_split.py",
             netscape_line(domain, "_visited", "1", exp)]
    n = 0
    for pair in cookie_str.split(";"):
        pair = pair.strip()
        if "=" not in pair:
            continue
        k, v = pair.split("=", 1)
        k, v = k.strip(), v.strip()
        if not k:
            continue
        lines.append(netscape_line(domain, k, v, exp))
        n += 1
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    log(f"已从粘贴的 cookie 生成 {n} 个字段 -> {path}")


def find_node():
    for c in [NODE_DEFAULT, shutil.which("node")]:
        if c and os.path.exists(c):
            return c
    return None


def ytdlp_base(ytdlp, ffmpeg_bin, proxy, site, yt_client="android"):
    """yt-dlp 统一基础参数: ffmpeg 路径 / node JS runtime / 代理 / YouTube player client"""
    cmd = [ytdlp, "--no-playlist"]
    if ffmpeg_bin:
        cmd += ["--ffmpeg-location", ffmpeg_bin]
    node = find_node()
    if node:
        cmd += ["--js-runtimes", f"node:{node}"]
    if proxy:
        cmd += ["--proxy", proxy]
    if site == "youtube":
        # android: 代理 IP 下绕过 bot 检测(稳定但只有低清muxed); tv: 配 cookie 可解锁 1080p+128k 音频
        cmd += ["--extractor-args", f"youtube:player_client={yt_client}"]
    return cmd


def fmt_lrc_time(t):
    """秒 -> LRC 时间 [mm:ss.xx] (百分秒)"""
    m = int(t // 60)
    s = t - m * 60
    return f"{m:02d}:{s:05.2f}"


def to_simplified(text):
    """繁体转简体 (OpenCC t2s)。兼容 LRC: 保留 [时间戳]/[标签] 前缀, 只转文本部分。
    未安装 opencc 时原样返回。"""
    try:
        from opencc import OpenCC
        cc = OpenCC("t2s")
    except ImportError:
        return text
    out = []
    for line in (text or "").splitlines():
        if line.startswith("[") and "]" in line:
            i = line.index("]")
            out.append(line[:i + 1] + cc.convert(line[i + 1:]))
        else:
            out.append(cc.convert(line))
    return "\n".join(out)


def parse_vtt(path):
    """解析 YouTube 字幕 VTT -> [(绝对秒, 文本), ...] (官方歌词来源)"""
    cues = []
    ts = None
    parts = []
    for raw in open(path, encoding="utf-8"):
        line = raw.strip()
        if "-->" in line:
            if ts is not None and parts:
                cues.append((ts, " ".join(parts)))
            m = re.match(r"(\d+):(\d{2}):(\d{2}\.\d{3})\s*-->", line)
            ts = (int(m.group(1)) * 3600 + int(m.group(2)) * 60 + float(m.group(3))) if m else None
            parts = []
        elif line and not line.startswith(("WEBVTT", "Kind:", "Language:")):
            parts.append(line)
    if ts is not None and parts:
        cues.append((ts, " ".join(parts)))
    return cues


def fetch_subs(ytdlp, ffmpeg_bin, proxy, site, yt_client, args, tmp, lang):
    """下载 YouTube 官方字幕 (zh-Hant 等, android client 无需 PO token) -> vtt 路径"""
    cmd = ytdlp_base(ytdlp, ffmpeg_bin, proxy, site, yt_client) + [
        "--write-subs", "--sub-langs", lang, "--sub-format", "vtt",
        "--skip-download", "-o", os.path.join(tmp, "subs.%(ext)s"), args.url]
    try:
        subprocess.run(cmd, check=True, capture_output=True, text=True,
                       encoding="utf-8", errors="replace", timeout=300)
    except subprocess.CalledProcessError:
        return None
    for f in os.listdir(tmp):
        if f.startswith("subs.") and f.endswith(".vtt"):
            return os.path.join(tmp, f)
    return None


def collect_subs_timed(ytdlp, ffmpeg_bin, proxy, site, yt_client, args, tmp, segments, lang):
    """下载官方字幕并按分段切成相对时间戳歌词; 失败返回 None (调用方回退 Whisper)"""
    subs_path = fetch_subs(ytdlp, ffmpeg_bin, proxy, site, yt_client, args, tmp, lang)
    if not subs_path:
        log(f"官方字幕 {lang} 获取失败, 回退 Whisper 转写")
        return None
    cues = parse_vtt(subs_path)
    timed_map = {}
    for seg in segments:
        st, en = seg["start"], seg["end"]
        timed = [(round(t - st, 3), to_simplified(x)) for t, x in cues if st <= t < en]
        if timed:
            timed_map[seg["idx"]] = timed
    log(f"官方字幕 {lang} 可用 ({len(cues)} 条 cue), 跳过 Whisper 转写")
    return timed_map


def build_lrc(segments, title="", artist="", album=""):
    """带时间戳的转写结果 -> LRC 同步歌词文本 (标准头 [ti:][ar:][al:] + [mm:ss.xx] 行)

    标准头必须写全: 网易云音乐等国产播放器解析 LYRICS 时需要 [ti:][ar:][al:] 头
    (参考 MusicTag 写入格式: [ti:歌名]\\n[ar:歌手]\\n[al:专辑]\\n[00:00.00]...)
    """
    lines = []
    if title:
        lines.append(f"[ti:{title}]")
    if artist:
        lines.append(f"[ar:{artist}]")
    if album:
        lines.append(f"[al:{album}]")
    for start, text in segments:
        lines.append(f"[{fmt_lrc_time(start)}]{text}")
    return "\n".join(lines)


def rebuild_lrc_header(lrc, theme="", title_hint=""):
    """重建 LRC 标准头: 去掉旧 [xx:] 头, 用主题/标题写全 [ti:][ar:][al:] (网易云兼容)"""
    body = []
    for line in (lrc or "").splitlines():
        s = line.strip()
        if s.startswith("[") and "]" in s:
            tag = s[1:s.index("]")]
            if re.match(r"^(ti|ar|al|by|offset|la|re|ve|au|length)$", tag, re.I):
                continue  # 跳过旧头部标签
        body.append(line)
    header = f"[ti:{theme}]" if theme else ""
    if title_hint:
        header += f"\n[ar:{title_hint}]"
        header += f"\n[al:{title_hint}]"
    return (header + "\n" + "\n".join(body)).strip() if header else "\n".join(body)


def fetch_title(ytdlp, url, ffmpeg_bin, proxy, site, yt_client="android"):
    """用 yt-dlp 取视频标题（不下载）"""
    cmd = ytdlp_base(ytdlp, ffmpeg_bin, proxy, site, yt_client) + \
        ["--skip-download", "--print", "%(title)s", url]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=90)
        if r.returncode == 0 and r.stdout.strip():
            return r.stdout.strip().splitlines()[0]
    except Exception:
        pass
    return ""


def build_dl_cmd(ytdlp, ffmpeg_bin, proxy, site, yt_client, args, tmp, fmt):
    dl_cmd = ytdlp_base(ytdlp, ffmpeg_bin, proxy, site, yt_client) + \
        ["-f", fmt, "-o", os.path.join(tmp, "audio.%(ext)s")]
    if args.cookies_text:
        domain = ".youtube.com" if site == "youtube" else ".bilibili.com"
        write_netscape_cookies(os.path.join(tmp, "cookies.txt"), args.cookies_text, domain)
        dl_cmd += ["--cookies", os.path.join(tmp, "cookies.txt")]
    elif args.cookies:
        dl_cmd += ["--cookies", args.cookies]
    elif args.browser:
        dl_cmd += ["--cookies-from-browser", args.browser]
    dl_cmd += [args.url]
    return dl_cmd


def download_audio(ytdlp, ffmpeg_bin, proxy, site, yt_client, args, tmp, fmt):
    """下载最佳音轨到 tmp/audio.*。

    YouTube 走多 client 轮询自动降级 (当前 client -> web -> android -> tv),
    规避代理 IP 下的 bot 检测/限流; 全部失败则抛出最后一个错误。
    """
    if site != "youtube":
        run(build_dl_cmd(ytdlp, ffmpeg_bin, proxy, site, yt_client, args, tmp, fmt))
        return
    order = []
    for c in (yt_client, "web", "android", "tv"):
        if c not in order:
            order.append(c)
    last_err = None
    for c in order:
        try:
            run(build_dl_cmd(ytdlp, ffmpeg_bin, proxy, site, c, args, tmp, fmt))
            return
        except subprocess.CalledProcessError as e:
            last_err = e
            log(f"{c} client 下载失败, 尝试下一个 client...")
    raise last_err


