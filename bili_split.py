def cmd_split(args):
    ffmpeg = find_exe("ffmpeg", args.ffmpeg, FFMPEG_DEFAULT)
    ytdlp = find_exe("yt-dlp", args.ytdlp, YTDLP_DEFAULT)
    cuts = parse_cuts(args.cuts)
    outdir = os.path.abspath(args.out)
    os.makedirs(outdir, exist_ok=True)
    tmp = os.path.join(outdir, "temp")
    os.makedirs(tmp, exist_ok=True)

    site = detect_site(args.url)
    log(f"站点识别: {site} | {args.url}")
    # YouTube 默认走本机代理 (国内直连被墙); 也可 --proxy 显式指定
    proxy = args.proxy
    if not proxy and site == "youtube":
        proxy = "http://127.0.0.1:7890"
        log(f"YouTube 检测, 自动使用代理 {proxy} (可用 --proxy 覆盖)")

    # 0. 先取标题（apply 阶段写 artist 标签）
    ffmpeg_bin = os.path.dirname(ffmpeg)
    has_cookie = bool(args.cookies or args.cookies_text or args.browser)
    yt_client = args.yt_client or ("tv" if (site == "youtube" and has_cookie) else "android")
    title = fetch_title(ytdlp, args.url, ffmpeg_bin, proxy, site, yt_client)
    log(f"视频标题: {title or '(获取失败)'}")

    # 1. 下载最佳音轨 (YouTube 多 client 轮询: 当前client -> web -> android -> tv)
    log(f"下载音轨: {args.url}")
    download_audio(ytdlp, ffmpeg_bin, proxy, site, yt_client, args, tmp, args.format)
    audio = None
    for f in os.listdir(tmp):
        if f.startswith("audio."):
            audio = os.path.join(tmp, f)
    if not audio:
        raise SystemExit("下载失败: 未找到音轨文件")

    # 2. 解码为完整 wav（原采样率, 用于切 flac） + 16k mono（用于 whisper）
    full_hi = os.path.join(tmp, "full_hi.wav")
    full_16k = os.path.join(tmp, "full_16k.wav")
    run(ffmpeg_cmd(ffmpeg, ["-i", audio, "-vn", "-c:a", "pcm_s16le", full_hi]))
    run(ffmpeg_cmd(ffmpeg, ["-i", audio, "-vn", "-ar", "16000", "-ac", "1",
                            "-c:a", "pcm_s16le", full_16k]))

    # 3. 切割
    segments = []
    for i, (s, e) in enumerate(cuts, 1):
        tag = f"seg_{i:02d}"
        cut_flac(ffmpeg, full_hi, os.path.join(outdir, f"{tag}.flac"), s, e)
        cut_wav16(ffmpeg, full_16k, os.path.join(tmp, f"{tag}_w16.wav"), s, e)
        segments.append({"idx": i, "tag": tag, "start": s, "end": e,
                         "start_str": f"{s:.3f}", "end_str": f"{e:.3f}",
                         "theme": "", "lyrics_file": f"{tag}.txt"})

    with open(os.path.join(outdir, "cuts.json"), "w", encoding="utf-8") as f:
        json.dump({"url": args.url, "title_hint": title, "segments": segments},
                  f, ensure_ascii=False, indent=2)

    # 4. 歌词来源: 优先 YouTube 官方字幕(--subs-lang, 更准确), 否则 Whisper 转写
    subs_timed = None
    if args.subs_lang and site == "youtube":
        subs_timed = collect_subs_timed(ytdlp, ffmpeg_bin, proxy, site, yt_client,
                                        args, tmp, segments, args.subs_lang)

    log(f"加载 Whisper 模型: {args.model} (首次会自动下载, 走 hf-mirror 镜像)")
    from faster_whisper import WhisperModel
    model = WhisperModel(args.model, device="cpu", compute_type="int8")
    for seg in segments:
        wav16 = os.path.join(tmp, f"{seg['tag']}_w16.wav")
        txt = os.path.join(outdir, f"{seg['tag']}.txt")
        lrc_path = os.path.join(outdir, f"{seg['tag']}.lrc")
        log(f"转写 {seg['tag']} ({seg['start_str']} - {seg['end_str']}) ...")
        lang = args.lang or None
        if subs_timed and seg["idx"] in subs_timed:
            timed = subs_timed[seg["idx"]]
            info_lang = args.subs_lang
        else:
            seg_iter, info = model.transcribe(wav16, language=lang,
                                              beam_size=5, vad_filter=args.vad)
            timed = [(s.start, s.text.strip()) for s in seg_iter if s.text.strip()]
            info_lang = info.language
        text = "\n".join(t for _, t in timed)
        text = to_simplified(text)  # 繁体 -> 简体
        with open(txt, "w", encoding="utf-8") as f:
            f.write(text + "\n")
        # LRC 同步歌词 (embedded 滚动歌词; 标准头 [ti:][ar:][al:] + [mm:ss.xx] 时间戳)
        lrc = to_simplified(build_lrc(timed, title, artist=title, album=title))
        with open(lrc_path, "w", encoding="utf-8") as f:
            f.write(lrc + "\n")
        seg["lang"] = info_lang
        seg["lyrics_file"] = f"{seg['tag']}.txt"
        seg["lrc_file"] = f"{seg['tag']}.lrc"
        seg["lyrics_preview"] = text[:60].replace("\n", " / ")
        src = "字幕" if (subs_timed and seg["idx"] in subs_timed) else "whisper"
        log(f"  -> {len(text)} 字, {len(timed)} 句(带时间戳), 来源 {src}")

    # 5. 主题模板
    themes = os.path.join(outdir, "themes.json")
    with open(themes, "w", encoding="utf-8") as f:
        json.dump({"instructions": "为每段填 theme 字段(4-8字中文主题), 保存后运行 apply",
                   "segments": segments}, f, ensure_ascii=False, indent=2)
    log(f"完成! 输出目录: {outdir}")
    log(f"下一步: 读取各 seg_XX.txt 歌词, 填好 {themes} 的 theme, 再执行 apply")
    return outdir


def write_flac_tags(path, title="", artist="", lyrics_lrc="", comment="", lyrics_plain=""):
    """用 mutagen 写 FLAC Vorbis Comment 标签 (embedded 嵌入)。

    歌词字段说明 (FLAC 无官方字段, 两个事实标准):
      - LYRICS:            foobar2000 / MusicBee / Poweramp / MusicBrainz Picard 阵营
                           写入 LRC 同步歌词(带 [mm:ss.xx] 时间戳) -> 播放器逐行滚动
      - UNSYNCEDLYRICS:    Mp3tag / Bandcamp 阵营, 写入纯文本歌词(静态整块)
    双写以最大化兼容; 字段名必须大写 (小写 lyrics 多数播放器不认)。
    参考: MusicBrainz Picard 源码注释 "We read both but always write LYRICS"
    """
    from mutagen.flac import FLAC
    f = FLAC(path)
    if title:
        f["TITLE"] = [title]
    if artist:
        f["ARTIST"] = [artist]
    if lyrics_lrc:
        f["LYRICS"] = [lyrics_lrc]
    if lyrics_plain:
        f["UNSYNCEDLYRICS"] = [lyrics_plain]
    if comment:
        f["COMMENT"] = [comment]
    f.save()


