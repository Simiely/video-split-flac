"""
bili_split.py — B站视频按时间戳分段 + FLAC 提取 + Whisper 歌词转写 + 歌词嵌入 + 主题命名

成熟工作流（两阶段）:
  阶段一 split : yt-dlp 下载最佳音轨 -> 按时间戳精确切割为 flac -> faster-whisper 逐段转写歌词
                产出: seg_XX.flac / seg_XX.txt / cuts.json / themes.json(空主题模板)
  阶段二 apply : 读取 themes.json(人工或 AI 填好主题) -> 重命名为 "NN_主题.flac"
                -> 用 ffmpeg 把 LYRICS/TITLE/ARTIST/COMMENT 标签嵌入 flac

用法:
  python bili_split.py split  --url "https://www.bilibili.com/video/BVxxxx" \
      --cuts "0:00-12:34, 12:34-25:00, 25:00-40:12" \
      --model small --out ./output [--browser edge]

  python bili_split.py apply  --out ./output [--themes themes.json]

  python bili_split.py selftest --model tiny   # 不联网, 合成音频验证全链路

依赖: yt-dlp, ffmpeg, faster-whisper (pip install faster-whisper)
"""

