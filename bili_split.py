ILLEGAL = re.compile(r'[\\/:*?"<>|\r\n\t]')


def sanitize(name):
    return ILLEGAL.sub("_", name).strip().strip(".")


def cmd_apply(args):
    ffmpeg = find_exe("ffmpeg", args.ffmpeg, FFMPEG_DEFAULT)
    outdir = os.path.abspath(args.out)
    themes_path = args.themes or os.path.join(outdir, "themes.json")
    with open(themes_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    cuts_path = os.path.join(outdir, "cuts.json")
    meta = {}
    if os.path.exists(cuts_path):
        with open(cuts_path, "r", encoding="utf-8") as f:
            meta = json.load(f)
    url = meta.get("url", "")

    for seg in data["segments"]:
        theme = (seg.get("theme") or "").strip()
        if not theme:
            log(f"跳过 {seg['tag']}: 未填主题")
            continue
        tag = seg["tag"]
        src = os.path.join(outdir, f"{tag}.flac")
        if not os.path.exists(src):
            log(f"跳过 {tag}: 找不到 {src}")
            continue
        # 歌词文本
        lyrics = ""
        lf = os.path.join(outdir, seg.get("lyrics_file", f"{tag}.txt"))
        if os.path.exists(lf):
            with open(lf, "r", encoding="utf-8") as f:
                lyrics = f.read().strip()
        # LRC 同步歌词 (滚动)
        lrc = ""
        lrcf = os.path.join(outdir, seg.get("lrc_file", f"{tag}.lrc"))
        if os.path.exists(lrcf):
            with open(lrcf, "r", encoding="utf-8") as f:
                lrc = f.read().strip()
        if not lrc:
            lrc = lyrics  # 兜底: 无时间戳时降级为纯文本
        # 重建标准 LRC 头 (网易云兼容: [ti:歌名][ar:][al:] 必须写全)
        lrc = rebuild_lrc_header(lrc, theme, meta.get("title_hint", ""))
        # 目标名: NN_主题.flac
        num = f"{seg.get('idx', 0):02d}"
        dst = os.path.join(outdir, f"{num}_{sanitize(theme)}.flac")
        # 1) ffmpeg 纯拷贝改名 (不写 metadata, 保持流完整)
        run(ffmpeg_cmd(ffmpeg, ["-i", src, "-c", "copy", dst]))
        # 2) mutagen 写标签 (embedded): LYRICS=LRC滚动歌词, UNSYNCEDLYRICS=纯文本
        comment = f"源:{url} 段:{seg.get('start_str','')}-{seg.get('end_str','')}"
        write_flac_tags(dst, theme, meta.get("title_hint", ""), lrc, comment, lyrics)
        try:
            os.remove(src)
        except OSError as e:
            log(f"警告: 删除中间文件失败(可手动删): {src} ({e})")
        log(f"{tag}.flac -> {os.path.basename(dst)} (LYRICS 同步歌词 {len(lrc.splitlines())} 行 / UNSYNCEDLYRICS {len(lyrics)} 字)")
    log("apply 完成")


# ---------------- fetch-model: 下载 whisper 模型到本地 ----------------

def cmd_fetch(args):
    """下载 Systran/faster-whisper-<name> 到 models/ 目录（国内镜像优先, 失败切代理官方源）"""
    import ssl
    name = args.name
    dst_dir = os.path.join(args.dir, f"faster-whisper-{name}")
    os.makedirs(dst_dir, exist_ok=True)
    files = ["config.json", "model.bin", "tokenizer.json", "vocabulary.txt"]
    bases = [(f"https://hf-mirror.com/Systran/faster-whisper-{name}/resolve/main/", None),
             (f"https://huggingface.co/Systran/faster-whisper-{name}/resolve/main/", "http://127.0.0.1:7890")]
    socket.setdefaulttimeout(30)
    for fn in files:
        dst = os.path.join(dst_dir, fn)
        if os.path.exists(dst) and os.path.getsize(dst) > 0:
            log(f"跳过已有 {fn}")
            continue
        ok = False
        for base, proxy in bases:
            url = base + fn
            try:
                op = urllib.request.build_opener(
                    urllib.request.ProxyHandler({"https": proxy}) if proxy else urllib.request.ProxyHandler({}))
                with op.open(url, timeout=1800) as r, open(dst, "wb") as f:
                    f.write(r.read())
                log(f"OK {fn} ({os.path.getsize(dst)}B) via {url.split('/')[2]}")
                ok = True
                break
            except Exception as e:
                log(f"FAIL {fn} via {url.split('/')[2]}: {type(e).__name__}")
        if not ok:
            raise SystemExit(f"下载失败: {fn}")
    log(f"模型就绪: {dst_dir} (在 split 时用 --model 指定此目录)")


# ---------------- import-cookies: EditThisCookie JSON -> cookies.txt ----------------

def cmd_import_cookies(args):
    """把浏览器扩展导出的 cookie (EditThisCookie JSON 数组 或 name=value; 字符串) 转成 yt-dlp 的 cookies.txt"""
    with open(args.input, "r", encoding="utf-8") as f:
        data = json.load(f)
    if isinstance(data, str):
        # 形如 "SESSDATA=xxx; bili_jct=yyy" 的原始字符串
        write_netscape_cookies(args.output, data, domain=args.domain or ".youtube.com")
        return
    items = data if isinstance(data, list) else data.get("cookies", [])
    if not isinstance(items, list):
        raise SystemExit(f"无法识别的 cookie 格式: {args.input}")
    lines = ["# Netscape HTTP Cookie File", "# generated by bili_split.py import-cookies"]
    n = 0
    for c in items:
        if not isinstance(c, dict):
            continue
        name, value = c.get("name", ""), c.get("value", "")
        if not name:
            continue
        domain = c.get("domain", "") or args.domain or ".youtube.com"
        if not domain.startswith("."):
            domain = "." + domain
        path = c.get("path", "/") or "/"
        secure = "TRUE" if c.get("secure") else "FALSE"
        exp = int(c.get("expirationDate", 0)) if c.get("expirationDate") else 0
        lines.append(netscape_line(domain, name, value, exp, secure, path))
        n += 1
    with open(args.output, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    log(f"已从 {args.input} 导入 {n} 条 cookie -> {args.output} (注意: 文件含登录凭证, 勿外传/勿入库)")


# ---------------- 自测 ----------------

def cmd_selftest(args):
    """合成 3 段正弦波音频, 跑完整切割+转写+标签链路, 验证工具链可用"""
    ffmpeg = find_exe("ffmpeg", args.ffmpeg, FFMPEG_DEFAULT)
    tmp = tempfile.mkdtemp(prefix="bili_selftest_")
    wav = os.path.join(tmp, "synth.wav")
    sr, dur = 16000, 9
    import math
    import struct
    with wave.open(wav, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(sr)
        frames = bytearray()
        for n in range(sr * dur):
            v = int(12000 * math.sin(2 * math.pi * (440 if n % 3 == 0 else 554) * n / sr))
            frames += struct.pack("<h", v)
        w.writeframes(bytes(frames))
    log("自测: 切割 0-3/3-6/6-9 三段 -> flac + 转写(模型 " + args.model + ")")
    from faster_whisper import WhisperModel
    model = WhisperModel(args.model, device="cpu", compute_type="int8")
    for i, (s, e) in enumerate([(0, 3), (3, 6), (6, 9)], 1):
        tag = f"seg_{i:02d}"
        cut_flac(ffmpeg, wav, os.path.join(tmp, f"{tag}.flac"), s, e)
        cut_wav16(ffmpeg, wav, os.path.join(tmp, f"{tag}_w16.wav"), s, e)
        segments, info = model.transcribe(os.path.join(tmp, f"{tag}_w16.wav"),
                                          beam_size=5, vad_filter=True)
        txt = " ".join(x.text for x in segments)
        log(f"{tag}: 时长3s flac={os.path.getsize(os.path.join(tmp, tag+'.flac'))}B 转写={txt[:40]!r}")
    log("自测通过: 工具链可用")
    shutil.rmtree(tmp, ignore_errors=True)


